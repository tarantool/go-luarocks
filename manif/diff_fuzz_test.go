// Differential tests: every manifest text goes through the Go reader and
// writer and through upstream luarocks.persist, run by internal/luaref, and
// the two must agree. `go test` runs the seeds; `go test -run '^$' -fuzz
// FuzzXxx ./manif/` explores further.

