// maxInput bounds the fuzzed manifest texts.
const maxInput = 1 << 12

// manifestEdges are hand-picked edges of the persist format.
var manifestEdges = []string{
	"",
	"x = 1\n",
	"x = -1\n",
	"x = 0.1\n",
	"x = 1.5e3\n",
	"x = 99999999999999\n",
	"x = true\ny = false\n",
	"x = {}\n",
	"x = {{}}\n",
	"x = { 'a'; \"b\", }\n",
	"x = { [\"a b\"] = 1, [\"end\"] = 2 }\n",
	"x = { [1] = \"a\", [2] = \"b\" }\n",
	"x = { [-1] = \"a\", [1.5] = true, [4] = {} }\n",
	"x = { [\"1\"] = 1, [1] = \"one\", y = 2 }\n",
	"x = { \"a\", \"b\", k = \"v\" }\n",
	"x = [==[\na]]b]==]\n",
	"x = [[\n\nleading newline kept]]\n",
	"x = \"a\\\nb\"\n",
	"x = \"\\0\\1\\0012\\255\"\n",
	"x = \"tab\\tquote\\\"backslash\\\\\"\n",
	"-- a comment\nx = 1 -- trailing\n",
	"x = { y = { z = { 1, 2, 3 } } }\n",
	"_x1 = \"underscore key\"\n",
	"x = 1\nx = 2\n",
}

// manifestSeeds returns manifestEdges, the persist goldens (generated by
// upstream, see gen_goldens.sh) and the manifests of the upstream spec
// fixtures.
func manifestSeeds(f *testing.F) []string {
	f.Helper()

	var paths []string

	for _, glob := range []string{
		filepath.Join("testdata", "persist", "out", "*.out"),
		filepath.Join("..", "internal", "luarocks", "src", "spec", "fixtures", "a_repo", "manifest"),
		filepath.Join("..", "internal", "luarocks", "src", "spec", "fixtures", "a_repo", "manifest-5.?"),
	} {
		m, err := filepath.Glob(glob)
		if err != nil {
			f.Fatal(err)
		}

		paths = append(paths, m...)
	}

	sort.Strings(paths)

	seeds := make([]string, 0, len(manifestEdges)+len(paths))
	seeds = append(seeds, manifestEdges...)

	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil {
			f.Fatal(err)
		}

		seeds = append(seeds, string(b))
	}

	return seeds
}

func newVM(f *testing.F) *luaref.VM {
	f.Helper()

	vm, err := luaref.New()
	if err != nil {
		f.Fatalf("boot reference: %v", err)
	}

	f.Cleanup(vm.Close)

	return vm
}

// mixed is the comparable form of Parse's mixed-key table.
type mixed struct {
	Num map[int64]any
	Str map[string]any
}

// inexact stands for an integer Parse read that a Lua number cannot hold
// exactly, so it compares unequal to every number upstream can produce.
type inexact struct{ N int64 }

// goShape makes a Parse result comparable: numbers become float64 (or
// inexact) and mixed tables become mixed.
func goShape(v any) any {
	switch x := v.(type) {
	case int64:
		f := float64(x)
		if f >= math.MaxInt64 || int64(f) != x {
			return inexact{x}
		}

		return f
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = goShape(e)
		}

		return out
	case map[string]any:
		out := make(map[string]any, len(x))
		for k, e := range x {
			out[k] = goShape(e)
		}

		return out
	default:
		if mt, ok := manif.AsMixedTable(v); ok {
			m := mixed{Num: map[int64]any{}, Str: map[string]any{}}
			for k, e := range mt.Num {
				m.Num[k] = goShape(e)
			}

			for k, e := range mt.Str {
				m.Str[k] = goShape(e)
			}

			return m
		}

		return v
	}
}

// luaShape projects an upstream value (luaref.FromLua form) onto the shapes
// Parse documents: a table whose keys are exactly 1..N is a []any; one with
// both string and integer keys is a mixed table; any other is a
// map[string]any, its number keys stringified as Parse does. That last rule
// is a deliberate, documented loss in Parse ("sparse-numeric keys,
// stringified"), so it is applied here rather than reported; two upstream
// keys that it maps onto the same string are still a divergence.
func luaShape(v any) (any, error) {
	t, ok := v.(map[any]any)
	if !ok {
		return v, nil
	}

	var nums []float64

	strs := 0

	for k := range t {
		switch kk := k.(type) {
		case float64:
			nums = append(nums, kk)
		case string:
			strs++
		default:
			return nil, fmt.Errorf("key %v of type %T", k, k)
		}
	}

	sort.Float64s(nums)

	dense := strs == 0 && len(nums) > 0
	for i, n := range nums {
		dense = dense && n == float64(i+1)
	}

	if dense {
		out := make([]any, len(nums))
		for i := range nums {
			e, err := luaShape(t[float64(i+1)])
			if err != nil {
				return nil, err
			}

			out[i] = e
		}

		return out, nil
	}

	integral := true
	for _, n := range nums {
		integral = integral && n == math.Trunc(n) && math.Abs(n) < 1<<53
	}

	if strs > 0 && len(nums) > 0 && integral {
		m := mixed{Num: map[int64]any{}, Str: map[string]any{}}

		for k, e := range t {
			se, err := luaShape(e)
			if err != nil {
				return nil, err
			}

			switch kk := k.(type) {
			case float64:
				m.Num[int64(kk)] = se
			case string:
				m.Str[kk] = se
			}
		}

		return m, nil
	}

	out := map[string]any{}

	for k, e := range t {
		var key string

		switch kk := k.(type) {
		case float64:
			if kk == math.Trunc(kk) && math.Abs(kk) < 1<<63 {
				key = strconv.FormatInt(int64(kk), 10)
			} else {
				key = strconv.FormatFloat(kk, 'g', -1, 64)
			}
		case string:
			key = kk
		}

		if _, dup := out[key]; dup {
			return nil, fmt.Errorf("keys collide on %q", key)
		}

		se, err := luaShape(e)
		if err != nil {
			return nil, err
		}

		out[key] = se
	}

	return out, nil
}

// FuzzParse checks Parse against persist.load_into_table: whatever Parse
// accepts, upstream loads to the same data.
//
// Parse reads only the subset of Lua that persist writes and rejects the
// rest on purpose (see its doc), so a text only upstream accepts is not a
// divergence; FuzzWrite checks that the subset covers what upstream writes.
func FuzzParse(f *testing.F) {
	for _, s := range manifestSeeds(f) {
		f.Add(s)
	}

	vm := newVM(f)

	f.Fuzz(func(t *testing.T, src string) {
		if len(src) > maxInput {
			return
		}

		gv, err := manif.Parse([]byte(src))
		if err != nil {
			return
		}

		tbl, ok, msg, err := vm.LoadIntoTable(src)
		if err != nil {
			t.Fatalf("reference: %v", err)
		}

		if !ok {
			t.Fatalf("Parse accepts what upstream fails to load (%s): %q", msg, src)
		}

		if vmLexerArtifact(src) {
			return
		}

		lv, err := luaref.FromLua(tbl)
		if err != nil {
			t.Fatalf("reference: %v", err)
		}

		want, err := luaShape(lv)
		if err != nil {
			t.Fatalf("upstream data has no Parse shape (%v): %q", err, src)
		}

		if got := goShape(gv); !reflect.DeepEqual(got, want) {
			t.Fatalf("Parse and upstream disagree\nGo:       %#v\nupstream: %#v\ninput:    %q", got, want, src)
		}
	})
}

// leadingZero matches a number literal with a leading zero.
var leadingZero = regexp.MustCompile(`(^|[^0-9A-Za-z_.])0[0-9]`)

// vmLexerArtifact reports a text that the reference VM reads differently
// from LuaJIT, the VM Tarantool runs LuaRocks on, and so cannot judge:
//
//   - gopher-lua has no \x escape and reads "\x41" as "x41"; LuaJIT and
//     Parse read "A".
//   - gopher-lua reads a number with a leading zero as octal (0010 is 8);
//     LuaJIT and Parse read it as decimal (10).
//
// The checks are coarse — they look at the raw text, strings included — and
// only skip the value comparison, not the accept/reject one.
func vmLexerArtifact(src string) bool {
	return strings.Contains(src, `\x`) || leadingZero.MatchString(src)
}

// persistLossy reports a luaref.FromLua value that upstream's persist format
// itself cannot carry, so that reading back what Write wrote cannot be
// compared with what was written. Write reproduces upstream's bytes (checked
// first), so it inherits both cases:
//
//   - A string with a CR, value or key, goes into a long bracket, inside which
//     the Lua lexer turns every CR, CRLF and LFCR into LF.
//   - A key with a line break is written as "[" plus a long bracket plus "]",
//     that is "[[[...]]]", which Lua reads as a long string followed by a
//     stray "]": a syntax error.
//   - A number is written with 14 significant digits ("%.14g"), so one that
//     needs more comes back rounded.
func persistLossy(v any) bool {
	switch x := v.(type) {
	case string:
		return strings.Contains(x, "\r")
	case float64:
		back, err := strconv.ParseFloat(luaref.FormatNumber(x), 64)

		return err != nil || back != x
	case map[any]any:
		for k, e := range x {
			if ks, ok := k.(string); ok && strings.ContainsAny(ks, "\r\n") {
				return true
			}

			if persistLossy(e) {
				return true
			}
		}
	}

	return false
}

// toData converts a Parse result into luaref.ToLua input.
func toData(v any) any {
	switch x := v.(type) {
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = toData(e)
		}

		return out
	case map[string]any:
		out := make(map[string]any, len(x))
		for k, e := range x {
			out[k] = toData(e)
		}

		return out
	default:
		if mt, ok := manif.AsMixedTable(v); ok {
			out := map[any]any{}
			for k, e := range mt.Num {
				out[k] = toData(e)
			}

			for k, e := range mt.Str {
				out[k] = toData(e)
			}

			return out
		}

		return v
	}
}

// FuzzWrite checks Write against persist.save_from_table_to_string, on every
// value Parse reads: both refuse the same values, the texts are byte-equal
// (Write claims to be a byte-for-byte port), and upstream loads the Go text
// back to the value written.
func FuzzWrite(f *testing.F) {
	for _, s := range manifestSeeds(f) {
		f.Add(s)
	}

	vm := newVM(f)

	f.Fuzz(func(t *testing.T, src string) {
		if len(src) > maxInput {
			return
		}

		gv, err := manif.Parse([]byte(src))
		if err != nil {
			return
		}

		var buf bytes.Buffer

		gerr := manif.Write(&buf, gv)

		data, err := vm.ToLua(toData(gv))
		if err != nil {
			t.Fatalf("convert %#v: %v", gv, err)
		}

		want, ok, msg, err := vm.SaveFromTableToString(data)
		if err != nil {
			t.Fatalf("reference: %v", err)
		}

		if (gerr == nil) != ok {
			t.Fatalf("Write error: %v; upstream writes: %v (%s)\ninput: %q", gerr, ok, msg, src)
		}

		if gerr != nil {
			return
		}

		if got := buf.String(); got != want {
			t.Fatalf("Write and upstream disagree\nGo:\n%s\nupstream:\n%s\ninput: %q", got, want, src)
		}

		orig, err := luaref.FromLua(data)
		if err != nil {
			t.Fatalf("reference: %v", err)
		}

		if persistLossy(orig) {
			return
		}

		tbl, ok, msg, err := vm.LoadIntoTable(buf.String())
		if err != nil {
			t.Fatalf("reference: %v", err)
		}

		if !ok {
			t.Fatalf("upstream fails to load what Write wrote (%s): %q", msg, buf.String())
		}

		back, err := luaref.FromLua(tbl)
		if err != nil {
			t.Fatalf("reference: %v", err)
		}

		if !reflect.DeepEqual(back, orig) {
			t.Fatalf("upstream reads back other data\nwritten: %#v\nread:    %#v\ntext:    %q", orig, back, buf.String())
		}
	})
}
